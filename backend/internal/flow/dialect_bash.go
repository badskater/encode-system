// Package flow: BashDialect.
//
// BashDialect implements Dialect for Linux nodes. The design goal is
// injection-safety parity with PowerShellDialect: every interpolated
// value is POSIX-single-quoted, every comment is newline-flattened, and
// the step protocol markers (ENCODE_STEP / ENCODE_STEP_FAILED /
// ENCODE_JOB_DONE) emit the SAME marker text the PS dialect does, so the
// agent's stdout parser is dialect-agnostic.
//
// Per-dialect step templates (Task 1.2 scope):
//
//	The model still stores PowerShell source per StepTemplate. For the
//	bash dialect, StepBody inspects that source: a body that is pure
//	external commands (echo + plain argv) renders into a bash function;
//	a body using PowerShell-only cmdlets (Get-FileHash, Resolve-Tool,
//	pscustomobject, Join-Path, …) returns a clear render error. Task 1.3
//	will add Linux tool mappings behind this same StepBody seam — the
//	resolver itself does not change shape, only the dialect's view of
//	the resolved body does.
package flow

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/badskater/encode-system/backend/internal/model"
)

// BashDialect renders a job script as bash for Linux nodes.
type BashDialect struct{}

func (BashDialect) Ext() string { return ".sh" }

// Quote wraps a value in POSIX single quotes, escaping an embedded
// single quote via the '\” idiom (close, insert an escaped quote,
// reopen). Once inside '…' the shell treats the contents literally, so
// this is the primary injection guard for arbitrary series/episode/path
// values.
func (BashDialect) Quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// SafeIdent restricts an identifier to [a-z0-9_] (lowercased) so a step
// type or param key can never break out of its bare-token position.
func (BashDialect) SafeIdent(s string) string { return safeIdentAlpha(s) }

// Comment renders a value safe for interpolation into a comment: it
// flattens CR/LF to spaces so a smuggled line can never terminate a
// comment and become executable. It does NOT prefix '#' — the
// renderer's format strings provide the comment leader (mirroring
// psComment). The newline flattening is the actual security property.
func (BashDialect) Comment(s string) string {
	return stripNewlines(s)
}

// Preamble emits the bash header: shebang, strict mode, and the
// generated-by comment line. Mirrors the PS preamble's comment line but
// with '#' instead of the PS param block (bash has no $LibPath concept
// — EncodeLib is not dot-sourced; step bodies are self-contained).
func (d BashDialect) Preamble(j *model.Job, f *model.Flow, _ Vars) string {
	var b strings.Builder
	b.WriteString("#!/usr/bin/env bash\n")
	b.WriteString("set -euo pipefail\n\n")
	fmt.Fprintf(&b, "# Generated by encode-system controller - job %d, flow %s\n", j.ID, d.Comment(f.Name))
	b.WriteString("\n")
	return b.String()
}

// JobContext exports the shared context as bash variables (read by step
// bodies via "$BinDir", "$Series", etc.). Path joins use '/' since this
// dialect targets Linux nodes. The variable names mirror the PS $Job
// fields so step-template authors can map logic 1:1 once Task 1.3 adds
// Linux tool mappings.
func (d BashDialect) JobContext(j *model.Job, v Vars, episode, scriptName string) string {
	var b strings.Builder
	b.WriteString("# --- Job context (shared by every step) ---\n")
	fmt.Fprintf(&b, "BinDir=%s\n", d.Quote(v.BinDir))
	fmt.Fprintf(&b, "ScriptsDir=%s\n", d.Quote(v.ScriptsDir))
	fmt.Fprintf(&b, "ReleaseDir=%s\n", d.Quote(v.ReleaseDir))
	fmt.Fprintf(&b, "Series=%s\n", d.Quote(j.Series))
	fmt.Fprintf(&b, "Episode=%s\n", d.Quote(episode))
	fmt.Fprintf(&b, "EpisodeDir=%s\n", d.Quote(strings.TrimRight(v.ScriptsDir, "/")+"/"+j.EpisodeDir))
	fmt.Fprintf(&b, "ScriptFile=%s\n", d.Quote(strings.TrimRight(v.ScriptsDir, "/")+"/"+j.EpisodeDir+"/"+scriptName))
	fmt.Fprintf(&b, "HevcFile=%s\n", d.Quote(strings.TrimRight(v.ScriptsDir, "/")+"/"+j.EpisodeDir+"/"+EncodeHevcName))
	fmt.Fprintf(&b, "AudioFile=%s\n", d.Quote(strings.TrimRight(v.ScriptsDir, "/")+"/"+j.EpisodeDir+"/"+AudioWavName))
	fmt.Fprintf(&b, "OutputName=%s\n", d.Quote(OutputName(j.Series, episode, v.Tag)))
	fmt.Fprintf(&b, "ReleaseFolder=%s\n", d.Quote(ReleaseFolderName(v.Group, j.Series, v.Tag)))
	fmt.Fprintf(&b, "DefaultX265Args=%s\n", d.Quote(DefaultX265Args))
	fmt.Fprintf(&b, "Group=%s\n", d.Quote(v.Group))
	fmt.Fprintf(&b, "Tag=%s\n", d.Quote(v.Tag))
	fmt.Fprintf(&b, "DiscordWebhook=%s\n\n", d.Quote(v.DiscordWebhook))
	return b.String()
}

// ParamsLiteral renders the step's params as bash variable assignments
// that the step function reads from its environment. Unknown keys are
// dropped exactly like the PS paramsLiteral. Param keys are sanitized
// to [a-z0-9_] so they can be bare shell variable names. The variables
// are exported so the called function sees them.
func (d BashDialect) ParamsLiteral(st model.Step, t *model.StepTemplate) string {
	var b strings.Builder
	for _, pd := range t.Params {
		val := ""
		if v, ok := st.Params[pd.Key]; ok {
			val = v
		}
		key := d.SafeIdent(pd.Key)
		if key == "" {
			continue
		}
		fmt.Fprintf(&b, "    %s=%s\n", key, d.Quote(val))
	}
	return b.String()
}

// StepCall emits the per-step wrapper: the step comment, the start
// marker (identical text to PS), the params as local variables, the
// function invocation, and a failure handler that emits the
// ENCODE_STEP_FAILED marker (identical text to PS) and exits nonzero.
// bash's `set -e` (from the preamble) makes any nonzero function exit
// trigger the per-step ERR trap.
func (d BashDialect) StepCall(idx int, t *model.StepTemplate, st model.Step, safeType, fn string) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "\n# --- Step %d: %s ---\n", idx+1, d.Comment(t.Key))
	fmt.Fprintf(&b, "echo 'ENCODE_STEP %s start'\n", safeType)
	// Set up params as locals, then call the function. The ERR trap
	// fires on the first failing command inside the function, emits the
	// failure marker with the step name, and exits 1. trap is cleared
	// after the step so a later step's failure doesn't reuse it.
	fmt.Fprintf(&b, "trap 'echo \"ENCODE_STEP_FAILED %s $LINENO\"; exit 1' ERR\n", safeType)
	b.WriteString("{\n")
	b.WriteString(d.ParamsLiteral(st, t))
	fmt.Fprintf(&b, "%s\n", fn)
	fmt.Fprintf(&b, "} || { echo \"ENCODE_STEP_FAILED %s $LINENO\"; exit 1; }\n", safeType)
	b.WriteString("trap - ERR\n")
	return b.String(), nil
}

// JobDone emits the terminal marker (identical text to PS).
func (BashDialect) JobDone() string {
	return `echo 'ENCODE_JOB_DONE'`
}

// --- per-dialect template body validation ----------------------------

// bashFuncName matches a bash function declaration: `name () {` or
// `function name {`. Task 1.3 built-in bash templates declare their
// functions with the POSIX `name () {` form, so this regex locates the
// function name directly for both the definition (StepBody returns the
// source verbatim) and the call site (FuncName).
//
// REVIEW FOLLOW-UP #1 (func-name divergence, now resolved):
// Before Task 1.3, built-in templates stored PowerShell source and the
// bash dialect derived the function name two ways: FuncName used
// bashFuncName (or fell back to the PS `function <Name>` regex), while
// bashWrapFunction used bashFuncNameFromPS — two separate code paths
// that could diverge on a PS declaration shaped `function Foo () {`
// (with parens). Task 1.3 eliminates the divergence for built-ins: their
// bash sources declare functions with `name () {`, so bashFuncName is
// the ONE path that derives the name for both call and definition. The
// PS→bash translation path (bashWrapFunction + bashFuncNameFromPS) now
// serves ONLY user/custom templates; it still converts the PS name
// (lowercase, hyphens→underscores) consistently because
// bashFuncNameFromPS and FuncName's PS fallback both apply the same
// transform — but built-ins no longer touch that path at all.
var bashFuncName = regexp.MustCompile(`(?m)^\s*(?:function\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*\(\s*\)\s*\{`)

// psCmdletRe matches PowerShell Verb-Noun cmdlet calls (e.g.
// Get-FileHash, Resolve-Tool). Write-Output is the one cmdlet the bash
// dialect intentionally translates (to `echo`), so StepBody excludes
// it from the matches rather than refusing the whole body.
//
// TEMPORARY (review follow-up #2): this refuse-list and psCmdletRe
// exist ONLY to validate USER/CUSTOM templates (whose source is still
// PowerShell). Task 1.3 built-in templates BYPASS this list entirely —
// BashDialect.StepBody resolves built-ins to their Linux variant
// (builtinBashSources) before any PS inspection, so a built-in body
// containing cmdlets is never examined here. Once all user templates
// also carry per-dialect sources (or the UI stops accepting PS for
// custom steps), this list and the translate-or-refuse path can be
// removed.
var psCmdletRe = regexp.MustCompile(`\b[A-Z][a-z]+-[A-Z][a-zA-Z]+\b`)

// psCmdletRefuseRe catches PowerShell-only constructs that have no
// direct bash equivalent and are NOT translated by bashWrapFunction. If
// any appear, StepBody returns a render error.
//
// TEMPORARY: applies ONLY to user/custom templates (see psCmdletRe
// comment). Built-in templates resolve to their Linux variant before
// this list is consulted.
var psCmdletRefuseRe = []*regexp.Regexp{
	// PS variable sigils interpolated into commands ($($x…)).
	regexp.MustCompile(`\$\([A-Za-z]`),
	// PS hashtable/object literals.
	regexp.MustCompile(`\[pscustomobject\]`),
	regexp.MustCompile(`@\{`),
	// PS pipeline operators (ForEach-Object/Where-Object) — distinct
	// from the bash | pipe to an external command.
	regexp.MustCompile(`\|\s+ForEach-Object`),
	regexp.MustCompile(`\|\s+Where-Object`),
	// PS type accelerators / casts.
	regexp.MustCompile(`\[(?:string|int|bool|double|System\.)`),
}

// FuncName extracts the function name a template's source declares AND
// returns it in the bash form the rendered function will use (lowercase,
// hyphens → underscores). For Task 1.2 the stored source is PowerShell,
// so we locate the name via the PS `function <Name>` regex and convert
// it to a bash-safe identifier. When Task 1.3 stores bash-native
// templates, this will prefer the bash declaration form directly.
//
// CRITICAL: the name returned here MUST match the function name that
// bashWrapFunction emits, so the StepCall invocation resolves to the
// defined function.
func (BashDialect) FuncName(src string) string {
	// Prefer a bash declaration if present (forward-compatible with 1.3).
	if m := bashFuncName.FindStringSubmatch(src); m != nil {
		return m[1]
	}
	// Fall back to the PS function regex — the stored source is PS today.
	// Convert to a bash-safe identifier so the call matches the wrapped
	// definition produced by bashWrapFunction.
	if m := psFuncName.FindStringSubmatch(src); m != nil {
		return strings.ToLower(strings.ReplaceAll(m[1], "-", "_"))
	}
	return ""
}

// StepBody resolves a template's executable body for the bash dialect.
//
// Task 1.3 seam (built-in templates):
//   - If the template Key is in builtinBashSources, return that bash
//     source verbatim. This BYPASSES the PS cmdlet refuse-list entirely
//     (review follow-up #2): a built-in body containing cmdlets is never
//     inspected — the Linux variant is the source of truth.
//   - If the template Key is in builtinBashRefused, return a clear error
//     naming the template and the platform reason (e.g. dgindex → no
//     Linux equivalent).
//
// For USER/CUSTOM templates (anything not in either map), fall through
// to the Task 1.2 translate-or-refuse path: a body of pure external
// commands (echo + plain argv) renders into a bash function; a body
// using PowerShell-only cmdlets returns a clear render error. This path
// is the ONLY consumer of psCmdletRe/psCmdletRefuseRe (see the
// TEMPORARY comment there).
//
// The bash sources in builtinBashSources declare functions with the
// POSIX `name () {` form, so bashFuncName (the ONE name-derivation path
// for built-ins — review follow-up #1) locates the function name for
// both the definition and the call site.
func (BashDialect) StepBody(t *model.StepTemplate) (string, error) {
	// Built-in Linux mappings: resolve to the bash variant verbatim,
	// bypassing all PS inspection (the refuse-list is for user templates).
	if src, ok := builtinBashSources[t.Key]; ok {
		return src, nil
	}
	// Built-in templates with no Linux equivalent: refuse with a clear
	// platform reason so an operator reading the job log understands why.
	if reason, ok := builtinBashRefused[t.Key]; ok {
		return "", fmt.Errorf(
			"bash dialect cannot render built-in template %q on Linux: %s",
			t.Key, reason)
	}
	// User/custom templates: validate the PS body and translate the
	// wrapper. This is the ONLY path that uses psCmdletRe/psCmdletRefuseRe.
	bodyLines := psFunctionBodyLines(t.PowerShell)
	for _, line := range bodyLines {
		// Refuse PS-only constructs bashWrapFunction does not translate.
		for _, re := range psCmdletRefuseRe {
			if re.MatchString(line) {
				return "", fmt.Errorf(
					"bash dialect cannot render PowerShell-only template %q: "+
						"contains %q (provide a bash-native step template for Linux nodes)",
					t.Key, re.FindString(line))
			}
		}
		// Refuse any Verb-Noun cmdlet EXCEPT Write-Output (which
		// bashWrapFunction translates to echo).
		for _, m := range psCmdletRe.FindAllString(line, -1) {
			if m == "Write-Output" {
				continue
			}
			return "", fmt.Errorf(
				"bash dialect cannot render PowerShell-only template %q: "+
					"contains cmdlet %q (provide a bash-native step template for Linux nodes)",
				t.Key, m)
		}
	}
	// The body is validated: translate the wrapper to a bash function,
	// turning Write-Output lines into echo lines.
	return bashWrapFunction(t, t.PowerShell), nil
}

// psFunctionBodyLines returns the lines between the PS `function … {`
// declaration and the final closing `}` — i.e. the actual body, with
// the wrapper stripped. The param() line is included (it carries no
// commands); detection still skips it implicitly because it has no
// cmdlet-shaped token.
func psFunctionBodyLines(src string) []string {
	lines := strings.Split(src, "\n")
	var out []string
	skipDecl := true // skip until we pass the `function … {` line
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if skipDecl {
			if strings.HasPrefix(trimmed, "function ") {
				skipDecl = false
			}
			continue
		}
		out = append(out, line)
	}
	// Drop the trailing standalone `}` if present (the function close).
	if n := len(out); n > 0 && strings.TrimSpace(out[n-1]) == "}" {
		out = out[:n-1]
	}
	return out
}

// bashWrapFunction converts a PS `function Invoke-X { … }` block into a
// bash `invoke_x () { … }` function, lowercasing and replacing hyphens
// with underscores in the name, and translating PS `Write-Output "…"`
// lines into bash `echo '…'` lines (the only non-cmdlet construct we
// permit in the 1.2 subset). This keeps the rendered body self-contained
// bash while preserving the ENCODE_STEP marker text.
func bashWrapFunction(t *model.StepTemplate, body string) string {
	fn := bashFuncNameFromPS(t.PowerShell)
	lines := strings.Split(body, "\n")
	var out strings.Builder
	fmt.Fprintf(&out, "%s () {\n", fn)
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		// Drop the PS function declaration line.
		if strings.HasPrefix(trimmed, "function ") {
			continue
		}
		// Drop the standalone closing brace of the PS function.
		if trimmed == "}" {
			continue
		}
		// Drop the PS param() line (we pass params via env vars).
		if strings.HasPrefix(trimmed, "param(") || strings.HasPrefix(trimmed, "param (") {
			continue
		}
		// Translate Write-Output "…" → echo '…'.
		if echoLine, ok := psWriteOutputToEcho(trimmed); ok {
			out.WriteString("    " + echoLine + "\n")
			continue
		}
		// Everything else: pass through verbatim (already validated
		// free of cmdlets). Indent for readability.
		if trimmed == "" {
			out.WriteString("\n")
			continue
		}
		out.WriteString("    " + line + "\n")
	}
	out.WriteString("}\n")
	return out.String()
}

// bashFuncNameFromPS derives the bash function name from the PS function
// name in the template source (lowercase, hyphens → underscores).
func bashFuncNameFromPS(src string) string {
	if m := psFuncName.FindStringSubmatch(src); m != nil {
		return strings.ToLower(strings.ReplaceAll(m[1], "-", "_"))
	}
	return "step"
}

// psWriteOutputToEcho converts a `Write-Output "…"` line to an `echo '…'`
// line, returning ok=false if the line is not that shape. The marker
// text inside the quotes is preserved verbatim so the agent's parser is
// dialect-agnostic.
var psWriteOutputRe = regexp.MustCompile(`^Write-Output\s+"(.*)"\s*$`)

func psWriteOutputToEcho(line string) (string, bool) {
	m := psWriteOutputRe.FindStringSubmatch(line)
	if m == nil {
		return "", false
	}
	// The marker text (e.g. ENCODE_STEP foo 0) must be emitted verbatim.
	// Re-quote for bash single-quote safety.
	return "echo " + BashDialect{}.Quote(m[1]), true
}
